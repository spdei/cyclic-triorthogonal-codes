"""Cyclic codes over F_p of length n (gcd(n,p)=1) described by spectral supports.

A spectral support S is a union of p-cyclotomic cosets of Z_n. The cyclic code C(S) is
generated by g(x) = prod_{cosets c not contained in S} m_c(x), where m_c is the minimal
polynomial of alpha^s, s in c. Then dim C(S) = |S| and, under the Fourier transform
c -> (c(alpha^j))_j, C(S) consists of the vectors supported on S.

Coset data files have the format
    N p n
    C s1,s2,... c0,c1,...,cd        (coset elements, minimal polynomial low-to-high)
"""
import numpy as np
from math import gcd


def load_cosets(path):
    data, cur = {}, None
    for line in open(path):
        t = line.split()
        if not t:
            continue
        if t[0] == 'N':
            cur = (int(t[1]), int(t[2]))
            data[cur] = []
        else:
            data[cur].append((tuple(map(int, t[1].split(','))), [int(x) for x in t[2].split(',')]))
    return data


def polymul(a, b, p):
    r = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        if x:
            for j, y in enumerate(b):
                r[i + j] = (r[i + j] + x * y) % p
    return r


def generator_polynomial(cosets, S, p):
    S = set(S)
    g = [1]
    for c, mp in cosets:
        if not set(c) <= S:
            g = polymul(g, mp, p)
    return g


def code_basis(n, cosets, S, p):
    """Generator matrix (|S| x n) of the cyclic code with spectral support S."""
    g = generator_polynomial(cosets, S, p)
    deg = len(g) - 1
    K = n - deg
    B = np.zeros((K, n), dtype=np.int64)
    for j in range(K):
        B[j, j:j + deg + 1] = g
    return B


def sumset(S, n, k):
    """k-fold sumset S+...+S in Z_n (k >= 1)."""
    T = {0}
    for _ in range(k):
        T = {(a + b) % n for a in T for b in S}
    return T


def is_union_of_cosets(S, n, p):
    S = set(S)
    return all((s * p) % n in S for s in S)


def canonical_support(S, n):
    """Representative of the orbit of S under multipliers u in Z_n^* (coordinate permutations)."""
    units = [u for u in range(1, n) if gcd(u, n) == 1]
    return min(tuple(sorted((u * e) % n for e in S)) for u in units)


def cyclic_shift(B, s=1):
    return np.roll(B, s, axis=1)
